/**
 * Generates supabase/seed.sql from the TypeScript seed data (single source of sample data).
 * Run: pnpm db:seed-sql   then apply with `supabase db reset` or paste into the SQL editor.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { seedCategories } from "../shared/src/lib/seed/categories";
import { seedPosts } from "../shared/src/lib/seed/posts";
import { seedProducts } from "../shared/src/lib/seed/products";
import { seedReviews } from "../shared/src/lib/seed/reviews";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const catId = (slug: string) => `(select id from public.categories where slug = ${q(slug)})`;
const prodId = (legacy: string) => `(select id from public.products where legacy_id = ${q(legacy)})`;

export function buildSeedSql(): string {
  const out: string[] = ["-- Generated by scripts/gen-seed-sql.ts. SAMPLE DATA: replace before launch.", "begin;", ""];

  const ordered = [...seedCategories].sort((a, b) => Number(Boolean(a.parentSlug)) - Number(Boolean(b.parentSlug)));
  for (const c of ordered) {
    out.push(
      `insert into public.categories (slug, name, parent_id, intro, blurb, image, sort_order, seo_title, seo_description, faqs) values (${[
        q(c.slug), q(c.name), c.parentSlug ? catId(c.parentSlug) : "null", q(c.intro), q(c.blurb), q(c.image),
        String(c.sortOrder), q(c.seoTitle), q(c.seoDescription), j(c.faqs),
      ].join(", ")}) on conflict (slug) do nothing;`,
    );
  }
  out.push("");

  for (const p of seedProducts) {
    out.push(
      `insert into public.products (legacy_id, slug, category_id, subcategory_id, title, summary, description, how_to_use, specs, material, colour, price, mrp, meesho_url, meesho_price, price_checked_at, rating, review_count, stock, is_bestseller, is_flash_sale, faqs, created_at) values (${[
        q(p.id), q(p.slug), catId(p.categorySlug), catId(p.subcategorySlug), q(p.title), q(p.summary), q(p.description),
        arr(p.howToUse), j(p.specs), q(p.material), q(p.colour), String(p.price), String(p.mrp), q(p.meeshoUrl ?? ""),
        String(p.meeshoPrice ?? 0), q(p.priceCheckedAt), String(p.rating), String(p.reviewCount), String(p.stock),
        String(p.isBestseller), String(p.isFlashSale), j(p.faqs), q(p.createdAt),
      ].join(", ")}) on conflict (slug) do nothing;`,
    );
    p.images.forEach((img, i) =>
      out.push(`insert into public.product_images (product_id, src, alt, sort_order) values (${prodId(p.id)}, ${q(img.src)}, ${q(img.alt)}, ${i});`),
    );
  }
  out.push("");

  for (const r of seedReviews) {
    out.push(
      `insert into public.reviews (product_id, author, city, rating, title, body, photos, verified, is_approved, created_at) values (${[
        prodId(r.productId), q(r.author), q(r.city), String(r.rating), q(r.title), q(r.body), arr(r.photos), String(r.verified), "true", q(r.createdAt),
      ].join(", ")});`,
    );
  }
  out.push("");

  for (const p of seedPosts) {
    out.push(
      `insert into public.blog_posts (slug, title, excerpt, body, faqs, cover, author, is_published, published_at, updated_at) values (${[
        q(p.slug), q(p.title), q(p.excerpt), j(p.body), j(p.faqs), q(p.cover), q(p.author), "true", q(p.publishedAt), q(p.updatedAt),
      ].join(", ")}) on conflict (slug) do nothing;`,
    );
  }
  out.push("", "commit;", "");
  return out.join("\n");
}

if (process.argv[1]?.endsWith("gen-seed-sql.ts")) {
  writeFileSync(join(process.cwd(), "supabase", "seed.sql"), buildSeedSql());
  console.log("Wrote supabase/seed.sql");
}
